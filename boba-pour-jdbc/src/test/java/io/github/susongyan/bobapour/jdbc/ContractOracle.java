package io.github.susongyan.bobapour.jdbc;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import javax.sql.DataSource;

import org.h2.jdbcx.JdbcDataSource;

import io.github.susongyan.bobapour.config.ConfigLoader;
import io.github.susongyan.bobapour.config.model.PourConfig;

/**
 * 契约测试矩阵的对拍 oracle（T5，D8）：同一 H2 内嵌库上并置"原生直连"与"pour 包装"两条路径，
 * 逐契约断言行为一致——结果相等，或两侧异常类一致（异常行为本身是 JDBC 契约的一部分）。
 * pour 侧一律走反射构造形态（dataSourceClassName+props），使 D12 反射路径在矩阵中被全量行使。
 */
final class ContractOracle {

    static final String URL = "jdbc:h2:mem:contract;DB_CLOSE_DELAY=-1";

    private static final DataSource RAW_POOL = rawPool();
    private static final PourDataSource POUR_POOL = new PourDataSource(passthroughConfig());

    private ContractOracle() {
    }

    /** 原生路径：部署方池实例（H2 自带 JdbcDataSource）。 */
    static JdbcDataSource rawPool() {
        final JdbcDataSource pool = new JdbcDataSource();
        pool.setURL(URL);
        pool.setUser("sa");
        return pool;
    }

    /** 直通配置（无分片/加密/广播），datasources 节即反射构造素材。 */
    static PourConfig passthroughConfig() {
        return ConfigLoader.load(String.join("\n",
                "datasources:",
                "  ds_0:",
                "    className: org.h2.jdbcx.JdbcDataSource",
                "    props:",
                "      URL: " + URL,
                "      user: sa",
                ""));
    }

    static PourDataSource pourPool() {
        return POUR_POOL;
    }

    /** 建表与种子（幂等）。 */
    static void bootstrap() throws SQLException {
        try (Connection conn = RAW_POOL.getConnection(); Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE TABLE IF NOT EXISTS t_contract ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "name VARCHAR(64) NOT NULL, "
                    + "amount DECIMAL(10,2), "
                    + "created TIMESTAMP)");
            try (ResultSet rs = stmt.executeQuery("SELECT COUNT(*) FROM t_contract")) {
                rs.next();
                if (0 == rs.getLong(1)) {
                    stmt.executeUpdate("INSERT INTO t_contract(name, amount, created) VALUES "
                            + "('seed_a', 12.50, TIMESTAMP '2026-01-15 10:30:00'), "
                            + "('seed_b', 7.25, TIMESTAMP '2026-02-20 09:00:00'), "
                            + "('seed_c', 99.99, TIMESTAMP '2026-03-31 23:59:59')");
                }
            }
        }
    }

    /** 对拍探针：在给定连接上执行并返回可比较结果（List/String/Number/Boolean 等值语义对象）。 */
    interface Probe {
        Object run(Connection connection) throws SQLException;
    }

    /** 带标签探针：数据变更型用例以互异标签隔离两侧运行，避免共享库上的计数串扰。 */
    interface TaggedProbe {
        Object run(Connection connection, String tag) throws SQLException;
    }

    /** 对拍断言：结果相等，或异常类一致（含"一侧抛一侧不抛"的失衡即失败）。 */
    static void assertParity(final Probe probe) throws SQLException {
        bootstrap();
        verifyParity(quiet(c -> probe.run(c), RAW_POOL), quiet(c -> probe.run(c), POUR_POOL));
    }

    static void assertParity(final TaggedProbe probe) throws SQLException {
        bootstrap();
        verifyParity(quiet(c -> probe.run(c, "raw"), RAW_POOL), quiet(c -> probe.run(c, "pour"), POUR_POOL));
    }

    private static Object quiet(final Probe probe, final DataSource pool) {
        try (Connection conn = pool.getConnection()) {
            return probe.run(conn);
        } catch (final Throwable t) {
            return t;
        }
    }

    private static void verifyParity(final Object fromRaw, final Object fromPour) {
        if (fromRaw instanceof Throwable) {
            assertTrue(fromPour instanceof Throwable,
                    "原生抛 [" + fromRaw + "] 而 pour 未抛，结果=" + fromPour);
            assertEquals(fromRaw.getClass(), fromPour.getClass(),
                    "异常类不一致：原生=" + fromRaw.getClass().getSimpleName());
        } else {
            assertFalse(fromPour instanceof Throwable,
                    "pour 抛 [" + fromPour + "] 而原生正常，结果=" + fromRaw);
            assertEquals(fromRaw, fromPour, "结果不相等");
        }
    }
}

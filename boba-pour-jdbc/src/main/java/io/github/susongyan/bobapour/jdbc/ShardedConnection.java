    // ---------- 执行链（语句层共用） ----------

    /** 决策链全产物（裁决在 MergePlan，解析异常包装为执行前拒绝——同 DecisionChain 口径）。 */
    static final class Routed {

        final BoundStatement bound;
        final MergePlan plan;
        final RewriteResult units;

        Routed(final BoundStatement bound, final MergePlan plan, final RewriteResult units) {
            this.bound = bound;
            this.plan = plan;
            this.units = units;
        }
    }

    Routed route(final String sql) {
        final MetadataSnapshot snapshot = owner.snapshot();
        final io.github.susongyan.bobachop.ast.Statement statement;
        try {
            statement = BobaChop.parse(sql, DialectProfile.MYSQL);
        } catch (final UnsupportedSyntaxException e) {
            throw new UnsupportedQueryException("解析白名单", -1,
                    "白名单外构造（内核 UnsupportedSyntaxException）", e.getMessage());
        } catch (final ParseException e) {
            throw new UnsupportedQueryException("解析语法", -1, "语法错误（内核 ParseException）", e.getMessage());
        } catch (final LexException e) {
            throw new UnsupportedQueryException("解析词法", -1, "词法错误（内核 LexException）", e.getMessage());
        }
        final BoundStatement bound = Binder.bind(statement, snapshot);
        final RouteResult result = Router.route(bound, snapshot);
        final MergePlan plan = MergePlanner.plan(bound, result, snapshot);
        return new Routed(bound, plan, Rewriter.rewrite(sql, bound, result, plan, DialectProfile.MYSQL, snapshot));
    }

    /** 读路径：分片执行（单元执行器为 null 时默认直执行）→ 归并装配。 */
    ResultSet query(final Routed routed, final Executor.UnitQuery unit) throws SQLException {
        final QueryFanout fanout;
        if (null == unit) {
            fanout = Executor.openQuery(routed.units, owner.provider(), owner.snapshot().guards());
        } else {
            fanout = Executor.openQuery(routed.units, owner.provider(), owner.snapshot().guards(), unit);
        }
        return MergeExecutor.execute(routed.plan, routed.bound, fanout);
    }

    /** 写路径：分片执行 → 影响行数合并（求和/广播首副本；单元执行器为 null 时默认直执行）。 */
    int update(final Routed routed, final Executor.UnitUpdate unit) throws SQLException {
        if (null == unit) {
            return Executor.executeUpdate(routed.units, owner.provider(), routed.plan);
        }
        return Executor.executeUpdate(routed.units, owner.provider(), routed.plan, unit);
    }

    // ---------- 生命周期 ----------

    @Override
    public void close() throws SQLException {
        closed = true;
        SQLException failure = null;
        // 迭代副本：statement.close() 回调 statementClosed → 本列表移除自身
        for (final ShardedStatement statement : new ArrayList<ShardedStatement>(openStatements)) {
            try {
                statement.close();
            } catch (final SQLException e) {
                if (null == failure) {
                    failure = e;
                } else {
                    failure.addSuppressed(e);
                }
            }
        }
        openStatements.clear();
        if (null != metadataConnection) {
            try {
                metadataConnection.close();
            } catch (final SQLException e) {
                if (null == failure) {
                    failure = e;
                } else {
                    failure.addSuppressed(e);
                }
            }
        }
        if (null != failure) {
            throw failure;
        }
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    void requireOpen() throws SQLException {
        if (closed) {
            throw new SQLException("连接已关闭");
        }
    }

    // ---------- 事务与状态（v0 拒绝面，事务跟随挂 T9） ----------

    private SQLFeatureNotSupportedException deferred(final String what) {
        return new SQLFeatureNotSupportedException("分片模式 v0 不支持" + what
                + "（事务跟随/跨库状态面挂 T9）");
    }

    @Override
    public void setAutoCommit(final boolean autoCommit) throws SQLException {
        if (!autoCommit) {
            throw deferred("手动事务（当前每 fan-out 单元自动提交，多分片写非原子）");
        }
    }

    @Override
    public boolean getAutoCommit() {
        return true;
    }


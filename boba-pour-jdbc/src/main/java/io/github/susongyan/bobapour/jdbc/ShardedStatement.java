package io.github.susongyan.bobapour.jdbc;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLFeatureNotSupportedException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

/**
 * 分片引擎模式语句（T7）：静态 SQL 走完整决策链执行；v0 单结果集
 * （getMoreResults 恒 false）。归并游标只进只读——非默认 resultSetType/
 * Concurrency 在连接工厂已拒绝，语句面恒报只进只读。批量、游标定位、生成键
 * （D9）显式拒绝；maxRows/timeout 等上限语义跨分片无一致投影，非零设置显式拒绝
 * （提示级 fetchSize 接受但不二次传播——单元内 fetchSize 由快照 guards 决定，D3）。
 */
class ShardedStatement implements Statement {

    private final ShardedConnection connection;
    /** 打开中的归并结果集（close 级联归还 fan-out 连接）。 */
    private final List<ResultSet> openResults = new ArrayList<ResultSet>(1);
    private ResultSet current;
    private int updateCount = -1;
    private boolean closed;

    ShardedStatement(final ShardedConnection connection) {
        this.connection = connection;
    }

    // ---------- 执行 ----------

    @Override
    public ResultSet executeQuery(final String sql) throws SQLException {
        requireOpen();
        final ShardedConnection.Routed routed = connection.route(sql);
        if (routed.bound.shape().write) {
            throw new SQLException("写语句须用 executeUpdate（executeQuery 只接受读）");
        }
        final ResultSet merged = connection.query(routed, null);
        trackResult(merged);
        return merged;
    }

    @Override
    public int executeUpdate(final String sql) throws SQLException {
        return executeUpdate(sql, Statement.NO_GENERATED_KEYS);
    }

    @Override
    public int executeUpdate(final String sql, final int autoGeneratedKeys) throws SQLException {
        if (Statement.NO_GENERATED_KEYS != autoGeneratedKeys) {
            throw unsupportedGeneratedKeys();
        }
        requireOpen();
        final ShardedConnection.Routed routed = connection.route(sql);
        if (!routed.bound.shape().write) {
            throw new SQLException("读语句须用 executeQuery（executeUpdate 只接受写）");
        }
        final int count = connection.update(routed, null);
        markUpdate(count);
        return count;
    }

    @Override
    public int executeUpdate(final String sql, final int[] columnIndexes) throws SQLException {
        throw unsupportedGeneratedKeys();
    }

    @Override
    public int executeUpdate(final String sql, final String[] columnNames) throws SQLException {
        throw unsupportedGeneratedKeys();
    }

    /** 单结果集形态：写 = true（影响行数），读 = false（游标经 getResultSet 取）。 */
    @Override
    public boolean execute(final String sql) throws SQLException {
        requireOpen();
        final ShardedConnection.Routed routed = connection.route(sql);
        if (routed.bound.shape().write) {
            markUpdate(connection.update(routed, null));
            return true;
        }
        trackResult(connection.query(routed, null));
        return false;
    }

    @Override
    public boolean execute(final String sql, final int autoGeneratedKeys) throws SQLException {
        if (Statement.NO_GENERATED_KEYS != autoGeneratedKeys) {
            throw unsupportedGeneratedKeys();
        }
        return execute(sql);
    }

    @Override
    public boolean execute(final String sql, final int[] columnIndexes) throws SQLException {
        throw unsupportedGeneratedKeys();
    }

    @Override
    public boolean execute(final String sql, final String[] columnNames) throws SQLException {
        throw unsupportedGeneratedKeys();
    }

    // ---------- 结果面（单结果集） ----------

    @Override
    public ResultSet getResultSet() throws SQLException {
        requireOpen();
        return current;
    }

    @Override
    public int getUpdateCount() throws SQLException {
        requireOpen();
        return updateCount;
    }

    @Override
    public boolean getMoreResults() throws SQLException {
        return getMoreResults(Statement.CLOSE_CURRENT_RESULT);
    }

    @Override
    public boolean getMoreResults(final int currentIgnored) throws SQLException {
        requireOpen();
        closeCurrent();
        updateCount = -1;
        return false;
    }

    // ---------- 上限与提示（跨分片无一致投影的显式拒绝；提示级接受） ----------

    @Override
    public void setMaxRows(final int max) throws SQLException {
        if (0 != max) {
            throw new SQLFeatureNotSupportedException("maxRows 跨分片无一致投影"
                    + "（TopN 窗口由 LIMIT 子句表达，见 MergePlanner）");
        }
    }

    @Override
    public int getMaxRows() {
        return 0;
    }

    @Override
    public void setQueryTimeout(final int seconds) throws SQLException {
        if (0 != seconds) {
            throw new SQLFeatureNotSupportedException("queryTimeout 跨分片无一致投影"
                    + "（单元级超时随方言驱动参数模板，v0 不支持）");
        }
    }

    @Override
    public int getQueryTimeout() {
        return 0;
    }

    @Override
    public void setMaxFieldSize(final int max) throws SQLException {
        if (0 != max) {
            throw new SQLFeatureNotSupportedException("maxFieldSize 跨分片无一致投影");
        }
    }

    @Override
    public int getMaxFieldSize() {
        return 0;
    }

    @Override
    public void setFetchSize(final int rows) throws SQLException {
        if (0 > rows) {
            throw new SQLException("fetchSize 非负（提示级，不二次传播）");
        }
    }

    @Override
    public int getFetchSize() {
        return 0;
    }

    @Override
    public void setFetchDirection(final int direction) throws SQLException {
        if (ResultSet.FETCH_FORWARD != direction) {
            throw new SQLFeatureNotSupportedException("归并游标只进（FETCH_FORWARD）");
        }
    }

    @Override
    public int getFetchDirection() {
        return ResultSet.FETCH_FORWARD;
    }

    @Override
    public void setEscapeProcessing(final boolean enable) {
        // 接受不拦截：改写按原文 token 装配，转义处理归各分片原生驱动。
    }

    @Override
    public void setCursorName(final String name) throws SQLException {
        throw new SQLFeatureNotSupportedException("定位更新/删除游标名跨分片无语义");
    }

    @Override
    public void cancel() {
        // 同步执行无取消面（v0 串行编排，语句执行期不返回控制权）。
    }

    @Override
    public void setPoolable(final boolean poolable) throws SQLException {
        if (poolable) {
            throw new SQLFeatureNotSupportedException("语句池化归部署方池域（D12），本层无池化面");
        }
    }

    @Override
    public boolean isPoolable() {
        return false;
    }

    @Override
    public void closeOnCompletion() throws SQLException {
        throw new SQLFeatureNotSupportedException("语句随游标自动关闭跨分片 v0 不支持"
                + "（归并游标关闭已级联归还 fan-out 连接，语句生命周期归调用方）");
    }

    @Override
    public boolean isCloseOnCompletion() {
        return false;
    }

    // ---------- 批量与生成键（显式拒绝） ----------

    @Override
    public void addBatch(final String sql) throws SQLException {
        throw new SQLFeatureNotSupportedException("批量跨分片 v0 不支持（逐语句执行）");
    }

    @Override
    public void clearBatch() throws SQLException {
        throw new SQLFeatureNotSupportedException("批量跨分片 v0 不支持（逐语句执行）");
    }

    @Override
    public int[] executeBatch() throws SQLException {
        throw new SQLFeatureNotSupportedException("批量跨分片 v0 不支持（逐语句执行）");
    }

    @Override
    public ResultSet getGeneratedKeys() throws SQLException {
        throw unsupportedGeneratedKeys();
    }

    // ---------- 属性与生命周期 ----------

    @Override
    public int getResultSetType() {
        return ResultSet.TYPE_FORWARD_ONLY;
    }

    @Override
    public int getResultSetConcurrency() {
        return ResultSet.CONCUR_READ_ONLY;
    }

    @Override
    public int getResultSetHoldability() {
        return ResultSet.HOLD_CURSORS_OVER_COMMIT;
    }

    @Override
    public Connection getConnection() {
        return connection;
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public void close() throws SQLException {
        if (closed) {
            return;
        }
        closed = true;
        SQLException failure = null;
        for (final ResultSet resultSet : openResults) {
            try {
                resultSet.close();
            } catch (final SQLException e) {
                if (null == failure) {
                    failure = e;
                } else {
                    failure.addSuppressed(e);
                }
            }
        }
        openResults.clear();
        current = null;
        connection.statementClosed(this);
        if (null != failure) {
            throw failure;
        }
    }

    @Override
    public SQLWarning getWarnings() {
        return null;
    }

    @Override
    public void clearWarnings() {
    }

    @Override
    public boolean isWrapperFor(final Class<?> iface) {
        return iface.isInstance(this);
    }

    @Override
    public <T> T unwrap(final Class<T> iface) throws SQLException {
        if (iface.isInstance(this)) {
            return iface.cast(this);
        }
        throw new SQLFeatureNotSupportedException("分片语句不包装目标类型: " + iface.getName());
    }

    // ---------- 内部 ----------

    void requireOpen() throws SQLException {
        if (closed) {
            throw new SQLException("语句已关闭");
        }
        connection.requireOpen();
    }

    ShardedConnection connection() {
        return connection;
    }

    /** 读结果登记（预编译子类共用）。 */
    void trackResult(final ResultSet merged) {
        current = merged;
        updateCount = -1;
        openResults.add(merged);
    }

    /** 写结果登记（预编译子类共用）。 */
    void markUpdate(final int count) throws SQLException {
        closeCurrent();
        updateCount = count;
    }

    private void closeCurrent() throws SQLException {
        if (null != current) {
            current.close();
            openResults.remove(current);
            current = null;
        }
    }

    private static SQLFeatureNotSupportedException unsupportedGeneratedKeys() {
        return new SQLFeatureNotSupportedException("生成键跨分片无一致语义（D9；单分片透传用直通模式）");
    }
}
